# Shared presentation only: installation/removal decisions belong to the app.
def zai_message(level, text):
    import os
    import sys

    colours = {"ERROR": "1;31", "FAIL": "1;31", "WARN": "1;33", "NEXT": "1;36", "OK": "1;32"}
    label = f"[{level}]"
