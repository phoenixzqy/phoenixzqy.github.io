function Get-Architecture {
    try {
        switch ([System.Runtime.InteropServices.RuntimeInformation]::OSArchitecture.ToString()) {
            'X64' { return 'x64' }
            'Arm64' { return 'arm64' }
        }
    } catch {
        Write-Verbose 'RuntimeInformation is unavailable; falling back to the environment.'
    }
    $raw = $env:PROCESSOR_ARCHITEW6432
    if ([string]::IsNullOrWhiteSpace($raw)) { $raw = $env:PROCESSOR_ARCHITECTURE }
    switch ($raw) {
        'AMD64' { return 'x64' }
        'ARM64' { return 'arm64' }
    }
    Stop-Install "unsupported processor architecture: $raw. Published builds cover x64 and arm64."
}

function Save-Download([string] $url, [string] $destination) {
    for ($hop = 0; $hop -le 5; $hop++) {
        $uri = $null
        if (-not [Uri]::TryCreate($url, [UriKind]::Absolute, [ref] $uri)) {
            Stop-Install "invalid download URL: $url"
        }
        $localFixture = $hop -eq 0 -and (Get-ZaiEnv 'ZAI_RELEASE_MANIFEST_URL') -and
            $url -cmatch '^http://127\.0\.0\.1(?::[0-9]+)?(?:/|[?#]|$)' -and
            $uri.Host -ceq '127.0.0.1'
        if ($uri.Scheme -ne 'https' -and -not $localFixture) {
            Stop-Install "refusing to download over a non-HTTPS URL: $url"
        }
        # Windows PowerShell 5.1's Invoke-WebRequest can fail before returning
        # a response when MaximumRedirection is zero. Use the .NET transport
        # directly so every redirect is checked before the next request.
        $response = $null
        try {
            $request = [Net.HttpWebRequest]::Create($uri)
            $request.AllowAutoRedirect = $false
            $response = $request.GetResponse()
            $status = [int] $response.StatusCode
            if ($status -ge 300 -and $status -lt 400) {
                if ($localFixture) { Stop-Install "refusing to follow a plaintext redirect: $url" }
                $location = [string] $response.Headers['Location']
                if (-not $location) { Stop-Install "redirect without a Location: $url" }
                $url = [Uri]::new($uri, $location).AbsoluteUri
            } else {
                $stream = $response.GetResponseStream()
                try {
                    $file = [IO.File]::Create($destination)
                    try { $stream.CopyTo($file) } finally { $file.Dispose() }
                } finally { $stream.Dispose() }
                return
            }
        } catch {
            Stop-Install "download failed: $url ($($_.Exception.Message))"
        } finally {
            if ($null -ne $response) { $response.Close() }
        }
    }
    Stop-Install "too many download redirects: $url"
}

function Add-UserPath([string] $directory) {
    # The user PATH is read and written through the registry rather than
    # [Environment]::GetEnvironmentVariable/SetEnvironmentVariable: those expand
    # %VARIABLE% references on read and always write a plain string, which would
    # permanently freeze entries such as %USERPROFILE%\bin to today's value and
    # downgrade REG_EXPAND_SZ to REG_SZ.
    $key = [Microsoft.Win32.Registry]::CurrentUser.OpenSubKey('Environment', $true)
    if ($null -eq $key) {
        $key = [Microsoft.Win32.Registry]::CurrentUser.CreateSubKey('Environment')
    }
    try {
        $current = $key.GetValue('Path', '', [Microsoft.Win32.RegistryValueOptions]::DoNotExpandEnvironmentNames)
        $kind = if ($null -eq $key.GetValue('Path')) { [Microsoft.Win32.RegistryValueKind]::ExpandString } else { $key.GetValueKind('Path') }
        if ($null -eq $current) { $current = '' }
        $entries = @([string]$current -split ';' | Where-Object { $_ })
        $normalized = $directory.TrimEnd('\')
        foreach ($entry in $entries) {
            if ([Environment]::ExpandEnvironmentVariables($entry).TrimEnd('\') -ieq $normalized) {
                Write-Host "$directory is already on your user PATH."
                return
            }
        }
        $updated = (@($entries) + $directory) -join ';'
        $key.SetValue('Path', $updated, $kind)
        Write-Host "Added $directory to your user PATH."
    } finally {
        $key.Close()
    }
}

function Show-Activation([string] $directory, [string] $command) {
    # irm | iex runs in the calling PowerShell process. The bundled Python
    # installer and registry updates cannot change this process's environment.
    $separator = [IO.Path]::PathSeparator
    $normalized = $directory.TrimEnd([char[]]'\/')
    $present = @($env:PATH -split [regex]::Escape([string]$separator) |
        Where-Object { $_.TrimEnd([char[]]'\/') -ieq $normalized }).Count -gt 0
    if (-not $present) {
        if ([string]::IsNullOrEmpty($env:PATH)) { $env:PATH = $directory }
        else { $env:PATH = $directory + $separator + $env:PATH }
    }

    $quotedDirectory = "'" + $directory.Replace("'", "''") + "'"
    Write-Host ''
    Write-Host '[NEXT] Ready in this PowerShell session. Run:'
    $quotedCommand = "'" + $command.Replace("'", "''") + "'"
    Write-Host ("  & " + $quotedCommand)
    Write-Host ''
    Write-Host 'If the installer ran in a separate process, activate your calling PowerShell terminal:'
    Write-Host ('  $env:Path = ' + $quotedDirectory + ' + [IO.Path]::PathSeparator + $env:Path')
    Write-Host ("  & " + $quotedCommand)
}
function Install-Shortcut([string] $directory, [string] $name, [string] $command) {
    if (-not (Test-Path -LiteralPath (Join-Path $directory "$command.exe") -PathType Leaf)) { return }
    $launcher = Join-Path $directory "$name.cmd"
    $taken = (Get-Command $name -All -ErrorAction SilentlyContinue) -or
        (Get-Item -LiteralPath $launcher -Force -ErrorAction SilentlyContinue)
    # CMD also searches its current directory, unlike PowerShell.
    $currentDirectories = @($directory, [Environment]::CurrentDirectory)
    $location = Get-Location
    if ($location.Provider.Name -eq 'FileSystem') { $currentDirectories += $location.ProviderPath }
    $extensions = @('') + @($env:PATHEXT -split ';') + @('.exe', '.cmd', '.bat', '.com', '.ps1')
    foreach ($currentDirectory in $currentDirectories) {
        foreach ($extension in $extensions) {
            if (Get-Item -LiteralPath (Join-Path $currentDirectory ($name + $extension)) -Force -ErrorAction SilentlyContinue) {
                $taken = $true
            }
        }
    }
    # A PowerShell child of CMD shares the console's DOSKEY macros.
    if ($env:OS -eq 'Windows_NT') {
        $doskey = Join-Path $env:SystemRoot 'System32\doskey.exe'
        if (Test-Path -LiteralPath $doskey) {
            if (& $doskey /macros:cmd.exe | Where-Object { $_ -imatch ('^' + [regex]::Escape($name) + '=') }) {
                $taken = $true
            }
        }
    }
    if ($taken) {
        Write-Host "Skipped shortcut ${name}: the name is already taken."
        return
    }
    # A relative CMD launcher works in both PowerShell and CMD, forwards all
    # arguments, and always follows updates to the canonical executable.
    $content = "@echo off`r`nrem zai shortcut: $name -> $command`r`n`"%~dp0$command.exe`" %*`r`n"
    $bytes = [Text.Encoding]::ASCII.GetBytes($content)
    try {
        $stream = [IO.File]::Open($launcher, [IO.FileMode]::CreateNew, [IO.FileAccess]::Write, [IO.FileShare]::None)
    } catch [IO.IOException] {
        Write-Host "Skipped shortcut ${name}: the launcher could not be created."
        return
    }
    try { $stream.Write($bytes, 0, $bytes.Length) } finally { $stream.Dispose() }
    Write-Host "Installed shortcut: $name -> $command"
}
